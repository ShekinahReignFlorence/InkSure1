/**
 * Generates an authentic SVG data URL representing messy handwriting on lined paper
 */
function createHandwritingSvg(config: {
  bgHue: string;
  lines: string[];
  crossedOutWord?: string;
  marginNote?: string;
  blot?: boolean;
}): string {
  const { bgHue, lines, crossedOutWord, marginNote, blot } = config;

  const svgLines = lines
    .map(
      (text, idx) =>
        `<text x="40" y="${70 + idx * 45}" font-family="'Instrument Serif', cursive, 'Brush Script MT', sans-serif" font-size="28" fill="#1c2536" font-style="italic" letter-spacing="1">${text}</text>
         <line x1="30" y1="${75 + idx * 45}" x2="480" y2="${75 + idx * 45}" stroke="#cbd5e1" stroke-width="0.75" stroke-dasharray="3,3" />`
    )
    .join('');

  const crossSvg = crossedOutWord
    ? `<line x1="145" y1="112" x2="225" y2="112" stroke="#991b1b" stroke-width="3" stroke-linecap="round" />
       <line x1="140" y1="115" x2="230" y2="110" stroke="#1e293b" stroke-width="2" />`
    : '';

  const marginSvg = marginNote
    ? `<g transform="translate(430, 90) rotate(90)">
         <rect x="-10" y="-18" width="160" height="26" fill="#fef3c7" rx="3" stroke="#f59e0b" stroke-width="0.75" stroke-dasharray="2,2"/>
         <text x="0" y="0" font-family="'Plus Jakarta Sans', sans-serif" font-size="13" font-weight="600" fill="#92400e">📌 ${marginNote}</text>
       </g>`
    : '';

  const blotSvg = blot
    ? `<circle cx="280" cy="205" r="14" fill="#0f172a" opacity="0.88" />
       <path d="M 270 195 Q 260 185 275 190 Q 295 190 290 205 Q 295 220 280 215 Q 265 215 270 195 Z" fill="#0f172a" opacity="0.85" />
       <text x="272" y="235" font-family="'Plus Jakarta Sans', sans-serif" font-size="10" fill="#dc2626" font-weight="bold">[ink blot]</text>`
    : '';

  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 540 340" width="540" height="340">
    <defs>
      <filter id="paper-texture">
        <feTurbulence type="fractalNoise" baseFrequency="0.04" numOctaves="4" result="noise" />
        <feDiffuseLighting in="noise" lighting-color="${bgHue}" surfaceScale="1.2">
          <feDistantLight azimuth="45" elevation="60" />
        </feDiffuseLighting>
        <feBlend mode="multiply" in="SourceGraphic" result="blend" />
      </filter>
    </defs>
    <rect width="100%" height="100%" fill="${bgHue}" />
    <!-- Left red margin rule -->
    <line x1="32" y1="0" x2="32" y2="340" stroke="#f87171" stroke-width="1.5" opacity="0.7" />
    <!-- Blue rule lines -->
    ${[75, 120, 165, 210, 255, 300]
      .map((y) => `<line x1="0" y1="${y}" x2="540" y2="${y}" stroke="#e2e8f0" stroke-width="1" />`)
      .join('')}
    <!-- Handwriting text -->
    ${svgLines}
    ${crossSvg}
    ${marginSvg}
    ${blotSvg}
  </svg>`;

  return `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`;
}

